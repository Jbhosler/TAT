def _p(text: str, style: ParagraphStyle) -> Paragraph:
    return Paragraph(_xml_safe(text), style)


def _p_html(html: str, style: ParagraphStyle) -> Paragraph:
    """Paragraph with trusted mini-HTML (already escaped user bits)."""
    return Paragraph(html, style)


def _table_header_row(labels: List[str], styles: Dict[str, ParagraphStyle], aligns: Optional[List[str]] = None) -> List[Paragraph]:
    aligns = aligns or ["LEFT"] * len(labels)
    out = []
    for label, align in zip(labels, aligns):
        st = ParagraphStyle(
            f"th_{label}_{align}",
            parent=styles["th"],
            alignment=TA_RIGHT if align == "RIGHT" else TA_LEFT,
        )
        out.append(Paragraph(label.upper(), st))
    return out


def _brand_table_style(n_rows: int, subtotal_rows: Optional[List[int]] = None) -> TableStyle:
    cmds = [
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, 0), 0),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 6),
        ("TOPPADDING", (0, 1), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 1), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("LINEBELOW", (0, 0), (-1, 0), 1.25, AUOUR_NAVY),
        ("LINEBELOW", (0, 1), (-1, -2), 0.5, AUOUR_ROW_RULE),
    ]
    for idx in subtotal_rows or []:
        cmds.append(("BACKGROUND", (0, idx), (-1, idx), AUOUR_SUBTOTAL_BG))
    return TableStyle(cmds)


def _split_paragraphs(additional_text: Optional[str]) -> List[str]:
    """Split optional narrative into paragraphs on blank lines."""
    if not additional_text:
        return []
    normalized = str(additional_text).replace("\r\n", "\n").replace("\r", "\n")
    return [p.strip() for p in normalized.split("\n\n") if p.strip()]


def _asset_class_sort_key(ac: str, order_index: Dict[str, int]):
    ac_norm = (ac or "").strip()
    if ac_norm in {"Side Pocket", "Forced Sale"}:
        return (2, 9999, ac_norm)
    if ac in order_index:
        return (0, order_index[ac], ac)
    return (1, 9999, ac_norm)


def _build_holdings_table_rows(
    holdings: List[Dict[str, Any]],
    side: str,
    portfolio_total: float,
    asset_class_order: List[str],
    styles: Dict[str, ParagraphStyle],
) -> Tuple[List[List[Any]], List[int]]:
    grouped: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
    for r in holdings:
        grouped[_str(r.get("asset_class"))].append(r)
    order_index = {name: idx for idx, name in enumerate(asset_class_order)}

    rows: List[List[Any]] = [
        _table_header_row(
            ["Ticker", "Asset Class", "Value ($)", "Unrealized ($)", "% Total"],
            styles,
            ["LEFT", "LEFT", "RIGHT", "RIGHT", "RIGHT"],
        )
    ]
    subtotal_idxs: List[int] = []

    for asset_class in sorted(grouped.keys(), key=lambda ac: _asset_class_sort_key(ac, order_index)):
        items = grouped[asset_class]
        for h in items:
            ticker = _str(h.get("ticker")) if side == "current" else _str(h.get("ticker") or h.get("model_ticker"))
            val = _float(h.get("value"))
            unreal = _float(h.get("unrealized_gain_loss"))
            pct = (val / portfolio_total * 100) if portfolio_total else 0.0
            if unreal > 0:
                u_style = styles["td_green"]
                u_txt = f"{unreal:,.0f}"
            elif unreal < 0:
                u_style = styles["td_red"]
                u_txt = f"{unreal:,.0f}"
            else:
                u_style = styles["td_gray"]
                u_txt = "—"
            rows.append([
                _p(ticker, styles["td_strong"]),
                _p(asset_class, styles["td"]),
                Paragraph(_xml_safe(f"{val:,.0f}" if abs(val) >= 0.5 else "—"), styles["td_right"]),
                Paragraph(_xml_safe(u_txt), u_style),
                Paragraph(_xml_safe(_pct(pct, 1, blank_zero=True)), styles["td_right_muted"]),
            ])
        ac_val = sum(_float(h.get("value")) for h in items)
        ac_unreal = sum(_float(h.get("unrealized_gain_loss")) for h in items)
        ac_pct = (ac_val / portfolio_total * 100) if portfolio_total else 0.0
        rows.append([
            Paragraph("", styles["subtotal"]),
            Paragraph(_xml_safe(f"{asset_class} subtotal"), styles["subtotal"]),
            Paragraph(_xml_safe(f"{ac_val:,.0f}"), styles["subtotal_right"]),
            Paragraph(
                _xml_safe(f"{ac_unreal:,.0f}" if abs(ac_unreal) >= 0.5 else "—"),
                styles["subtotal_right"],
            ),
            Paragraph(_xml_safe(_pct(ac_pct, 1, blank_zero=True)), styles["subtotal_right"]),
        ])
        subtotal_idxs.append(len(rows) - 1)

    return rows, subtotal_idxs


