def _register_fonts() -> None:
    """Register Newsreader + Libre Franklin; fall back to Helvetica if missing."""
    global _FONTS_REGISTERED
    global _FONT_SERIF, _FONT_SERIF_MED, _FONT_SERIF_SEMI, _FONT_SERIF_ITALIC, _FONT_SERIF_MED_ITALIC
    global _FONT_SANS, _FONT_SANS_MED, _FONT_SANS_SEMI, _FONT_SANS_BOLD
    if _FONTS_REGISTERED:
        return
    _FONTS_REGISTERED = True
    fonts_dir = Path(__file__).resolve().parent / "fonts"
    mapping = [
        ("Newsreader", "Newsreader-Regular.ttf", "_FONT_SERIF"),
        ("Newsreader-Medium", "Newsreader-Medium.ttf", "_FONT_SERIF_MED"),
        ("Newsreader-SemiBold", "Newsreader-SemiBold.ttf", "_FONT_SERIF_SEMI"),
        ("Newsreader-Italic", "Newsreader-Italic.ttf", "_FONT_SERIF_ITALIC"),
        ("Newsreader-MediumItalic", "Newsreader-MediumItalic.ttf", "_FONT_SERIF_MED_ITALIC"),
        ("LibreFranklin", "LibreFranklin-Regular.ttf", "_FONT_SANS"),
        ("LibreFranklin-Medium", "LibreFranklin-Medium.ttf", "_FONT_SANS_MED"),
        ("LibreFranklin-SemiBold", "LibreFranklin-SemiBold.ttf", "_FONT_SANS_SEMI"),
        ("LibreFranklin-Bold", "LibreFranklin-Bold.ttf", "_FONT_SANS_BOLD"),
    ]
    g = globals()
    registered = set()
    for face, filename, var in mapping:
        path = fonts_dir / filename
        if path.is_file():
            try:
                pdfmetrics.registerFont(TTFont(face, str(path)))
                g[var] = face
                registered.add(face)
            except Exception:
                pass
    # Enable <i>/<b> tags for Newsreader / Libre Franklin in Paragraph mini-HTML.
    if {"Newsreader", "Newsreader-Italic", "Newsreader-SemiBold", "Newsreader-MediumItalic"} <= registered:
        pdfmetrics.registerFontFamily(
            "Newsreader",
            normal="Newsreader",
            bold="Newsreader-SemiBold",
            italic="Newsreader-Italic",
            boldItalic="Newsreader-MediumItalic",
        )
    if {"LibreFranklin", "LibreFranklin-Bold"} <= registered:
        pdfmetrics.registerFontFamily(
            "LibreFranklin",
            normal="LibreFranklin",
            bold="LibreFranklin-Bold",
            italic="LibreFranklin",
            boldItalic="LibreFranklin-Bold",
        )


def _float(v: Any) -> float:
    if v is None:
        return 0.0
    if isinstance(v, Decimal):
        return float(v)
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def _str(v: Any) -> str:
    if v is None:
        return "—"
    return str(v).strip() or "—"


def _xml_safe(v: Any) -> str:
    """Escape for ReportLab Paragraph mini-HTML."""
    if v is None:
        return "—"
    t = str(v).strip()
    if not t:
        return "—"
    return escape(t)


def _sell_grade(so: Dict[str, Any]) -> int:
    g = so.get("grade")
    if g is None:
        return 2
    try:
        return int(g)
    except (TypeError, ValueError):
        return 2


def _money(n: float, blank_zero: bool = False) -> str:
    if blank_zero and abs(n) < 0.5:
        return "—"
    sign = "-" if n < 0 else ""
    return f"{sign}${abs(n):,.0f}"


def _pct(n: float, decimals: int = 1, blank_zero: bool = False) -> str:
    if blank_zero and abs(n) < 0.05:
        return "—"
    return f"{n:.{decimals}f}%"


def _gain_retention_rate(net_gain_loss: float, pre_unrealized: float) -> Optional[float]:
    if abs(pre_unrealized) < 1e-9:
        return None
    return 100.0 - (net_gain_loss / pre_unrealized * 100.0)


