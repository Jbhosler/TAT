class StackedBar(Flowable):
    """Horizontal stacked allocation bar with 1px white dividers."""

    def __init__(self, segments: List[Tuple[float, colors.Color]], width: float, height: float = 22):
        super().__init__()
        self.segments = [(w, c) for w, c in segments if w > 0]
        self._bar_width = width
        self._bar_height = height

    def wrap(self, availWidth, availHeight):
        self.width = self._bar_width
        self.height = self._bar_height
        return self.width, self.height

    def draw(self):
        self.canv.setStrokeColor(AUOUR_BORDER)
        self.canv.setLineWidth(0.75)
        self.canv.setFillColor(colors.white)
        self.canv.rect(0, 0, self.width, self.height, stroke=1, fill=1)
        total = sum(w for w, _ in self.segments) or 1.0
        x = 0.0
        for i, (w, c) in enumerate(self.segments):
            seg_w = self.width * (w / total)
            self.canv.setFillColor(c)
            self.canv.rect(x, 0, seg_w, self.height, stroke=0, fill=1)
            if i < len(self.segments) - 1 and seg_w > 1:
                self.canv.setStrokeColor(colors.white)
                self.canv.setLineWidth(1)
                self.canv.line(x + seg_w, 0, x + seg_w, self.height)
            x += seg_w
        self.canv.setStrokeColor(AUOUR_BORDER)
        self.canv.setLineWidth(0.75)
        self.canv.rect(0, 0, self.width, self.height, stroke=1, fill=0)


class AllocationLegend(Flowable):
    """Wrapping chip+label legend (sample uses ~4 items/row, natural gaps)."""

    def __init__(
        self,
        items: List[Tuple[colors.Color, str]],
        width: float,
        chip: float = 8,
        font_size: float = 8.2,
        col_gap: float = 16,
        row_gap: float = 6,
    ):
        super().__init__()
        self.items = items
        self._avail_width = width
        self.chip = chip
        self.font_size = font_size
        self.col_gap = col_gap
        self.row_gap = row_gap
        self._rows: List[List[Tuple[colors.Color, str, float]]] = []

    def wrap(self, availWidth, availHeight):
        self.width = min(self._avail_width, availWidth)
        # Measure and wrap into rows (flex-wrap style, like the sample)
        self._rows = []
        row: List[Tuple[colors.Color, str, float]] = []
        x = 0.0
        for color, label in self.items:
            text_w = pdfmetrics.stringWidth(label, _FONT_SANS, self.font_size)
            item_w = self.chip + 5 + text_w
            if row and x + item_w > self.width:
                self._rows.append(row)
                row = []
                x = 0.0
            row.append((color, label, item_w))
            x += item_w + self.col_gap
        if row:
            self._rows.append(row)
        line_h = max(self.chip, self.font_size) + 2
        self.height = len(self._rows) * line_h + max(0, len(self._rows) - 1) * self.row_gap
        return self.width, self.height

    def draw(self):
        line_h = max(self.chip, self.font_size) + 2
        y = self.height - line_h
        for row in self._rows:
            # Distribute leftover horizontal space across gaps so the row
            # spans the full content width (avoids a left-clustered look).
            content_w = sum(item_w for _, _, item_w in row)
            gaps = max(0, len(row) - 1)
            if gaps:
                gap = max(self.col_gap, (self.width - content_w) / gaps)
            else:
                gap = 0.0
            # Cap gap so short final rows don't stretch awkwardly
            if gaps and gap > 36:
                gap = self.col_gap
            x = 0.0
            for color, label, item_w in row:
                self.canv.setFillColor(color)
                self.canv.rect(x, y + 1, self.chip, self.chip, stroke=0, fill=1)
                self.canv.setFillColor(AUOUR_NAVY_MUTED)
                self.canv.setFont(_FONT_SANS, self.font_size)
                self.canv.drawString(x + self.chip + 5, y + 1, label)
                x += item_w + gap
            y -= line_h + self.row_gap


class ComparisonBars(Flowable):
    """Current (navy) vs Proposed (brass) bars scaled to the max value across all rows."""

    def __init__(
        self,
        rows: List[Tuple[str, float, float]],
        width: float,
        label_width: float = 150,
        row_gap: float = 5,
    ):
        super().__init__()
        self.rows = rows
        self._avail_width = width
        self.label_width = label_width
        self.row_gap = row_gap
        self.bar_h = 8
        self.pair_gap = 4
        self.pct_w = 40
        self.row_h = self.bar_h * 2 + self.pair_gap + self.row_gap
        self._scale = max((max(c, p) for _, c, p in rows), default=1.0) or 1.0

    def wrap(self, availWidth, availHeight):
        # Must assign self.height here — draw() relies on it; if left at 0,
        # bars render below the reserved box and overlap following content.
        self.width = min(self._avail_width, availWidth)
        self.track_w = max(40.0, self.width - self.label_width - 14 - self.pct_w)
        self.height = len(self.rows) * self.row_h
        return self.width, self.height

    def draw(self):
        y = self.height - self.row_h
        for name, cur, prop in self.rows:
            self.canv.setFillColor(AUOUR_NAVY)
            self.canv.setFont(_FONT_SANS_MED, 9)
            label_y = y + self.bar_h + self.pair_gap / 2 - 1
            self.canv.drawString(0, label_y, name[:28])

            track_x = self.label_width + 12

            def draw_bar(value: float, color: colors.Color, bar_y: float, label: str):
                self.canv.setFillColor(AUOUR_TRACK)
                self.canv.rect(track_x, bar_y, self.track_w, self.bar_h, stroke=0, fill=1)
                fill_w = self.track_w * (value / self._scale) if self._scale else 0
                if fill_w > 0:
                    self.canv.setFillColor(color)
                    self.canv.rect(track_x, bar_y, fill_w, self.bar_h, stroke=0, fill=1)
                self.canv.setFillColor(AUOUR_NAVY_MUTED)
                self.canv.setFont(_FONT_SANS, 8.2)
                self.canv.drawRightString(
                    track_x + self.track_w + self.pct_w, bar_y + 0.5, label
                )

            draw_bar(cur, AUOUR_NAVY, y + self.bar_h + self.pair_gap, _pct(cur, 1, blank_zero=True))
            draw_bar(prop, AUOUR_BRASS, y, _pct(prop, 1, blank_zero=True))

            # Row rule between pairs only (not under the last row — avoids
            # colliding with the caption that follows the chart).
            rule_y = y - self.row_gap / 2
            if rule_y > self.row_gap:
                self.canv.setStrokeColor(AUOUR_ROW_RULE)
                self.canv.setLineWidth(0.5)
                self.canv.line(0, rule_y, self.width, rule_y)
            y -= self.row_h


