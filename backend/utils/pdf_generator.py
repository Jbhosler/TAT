class StatCard(Flowable):
    """Fixed-height impact summary card (equal boxes, sample = 108pt tall)."""

    def __init__(
        self,
        label: str,
        value: str,
        note: str,
        width: float,
        height: float = STAT_CARD_H,
        tinted: bool = False,
        green: bool = False,
    ):
        super().__init__()
        self.label = label
        self.value = value
        self.note = note
        self.width = width
        self.height = height
        self.tinted = tinted
        self.green = green

    def wrap(self, availWidth, availHeight):
        return self.width, self.height

    def draw(self):
        pad = STAT_CARD_PAD
        # Background + border (tinted card still gets a border in the sample)
        self.canv.setStrokeColor(AUOUR_BORDER)
        self.canv.setLineWidth(0.75)
        if self.tinted:
            self.canv.setFillColor(AUOUR_STAT_TINT)
            self.canv.rect(0, 0, self.width, self.height, stroke=1, fill=1)
        else:
            self.canv.setFillColor(colors.white)
            self.canv.rect(0, 0, self.width, self.height, stroke=1, fill=0)

        # Label
        self.canv.setFillColor(AUOUR_GRAY)
        self.canv.setFont(_FONT_SANS, 7)
        self.canv.drawString(pad, self.height - pad - 7, self.label.upper())

        # Value
        self.canv.setFillColor(AUOUR_GREEN if self.green else AUOUR_NAVY)
        self.canv.setFont(_FONT_SERIF_SEMI if self.green else _FONT_SERIF, 22)
        self.canv.drawString(pad, self.height - pad - 36, self.value)

        # Note — wrap manually to fixed card width
        self.canv.setFillColor(AUOUR_GRAY_MID)
        self.canv.setFont(_FONT_SANS, 8)
        max_w = self.width - 2 * pad
        words = self.note.split()
        lines: List[str] = []
        cur = ""
        for word in words:
            trial = f"{cur} {word}".strip()
            if self.canv.stringWidth(trial, _FONT_SANS, 8) <= max_w:
                cur = trial
            else:
                if cur:
                    lines.append(cur)
                cur = word
        if cur:
            lines.append(cur)
        # Anchor notes near bottom of card
        line_h = 11
        y = pad + line_h * (len(lines) - 1)
        for line in lines:
            self.canv.drawString(pad, y, line)
            y -= line_h


